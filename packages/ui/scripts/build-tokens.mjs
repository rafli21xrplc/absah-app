// Generates packages/ui/src/tokens.ts and packages/ui/src/tokens.css from design/ds/absah/tokens.json.
//   pnpm tokens:build
// tokens.json is the only source of colour, type, spacing and radius. Nothing here invents a value; the only
// additions are plumbing: the next/font hook in --font-sans and the Tailwind namespace resets.
// The output is deterministic (input order, LF, trailing newline), so two runs give identical files.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const SOURCE = join(here, '../../../design/ds/absah/tokens.json');
export const TS_OUT = join(here, '../src/tokens.ts');
export const CSS_OUT = join(here, '../src/tokens.css');

// The CSS variable next/font/local sets on <html> (see app/fonts.ts in apps/web and apps/kiosk).
export const FONT_VARIABLE = '--font-plus-jakarta';

const HEADER = 'GENERATED by packages/ui/scripts/build-tokens.mjs from design/ds/absah/tokens.json. Do not edit; run `pnpm tokens:build`.';

const q = (s) => JSON.stringify(s);

/** Throws on anything the generator does not understand, so a new kind of token is never dropped silently. */
function check(tokens) {
  if (!tokens.color?.themes || !tokens.color?.tokens) throw new Error('tokens.json: color.themes and color.tokens are required');
  const themes = tokens.color.themes.map((t) => t.id);
  if (themes.join() !== 'light,dark') throw new Error(`tokens.json: expected themes light,dark, got ${themes.join()}`);
  for (const t of tokens.color.tokens) {
    for (const theme of themes) {
      if (!/^#[0-9A-F]{6}$/.test(t.value?.[theme] ?? '')) throw new Error(`tokens.json: ${t.name}.${theme} must be #RRGGBB`);
    }
  }
  for (const key of Object.keys(tokens)) {
    if (!['name', 'version', 'color', 'type', 'spacing', 'radius'].includes(key)) throw new Error(`tokens.json: unknown section "${key}"`);
  }
  const styleKeys = new Set(['name', 'fontSize', 'lineHeight', 'fontWeight', 'letterSpacing', 'fontVariantNumeric']);
  for (const g of tokens.type.groups) {
    for (const s of g.styles) {
      for (const k of Object.keys(s)) if (!styleKeys.has(k)) throw new Error(`tokens.json: type style ${s.name} has unknown key "${k}"`);
    }
  }
}

export function buildTs(tokens) {
  check(tokens);
  const out = [`// ${HEADER}`, ''];
  out.push('export const color = {');
  for (const t of tokens.color.tokens) out.push(`  ${q(t.name)}: { light: ${q(t.value.light)}, dark: ${q(t.value.dark)} },`);
  out.push('} as const;', '', 'export type ColorName = keyof typeof color;', "export type ThemeName = 'light' | 'dark';", '');
  out.push(`export const fontFamily = ${q(tokens.type.families.sans)};`, '');
  out.push('export const text = {');
  for (const g of tokens.type.groups) {
    for (const s of g.styles) {
      const fields = [`fontSize: ${q(s.fontSize)}`, `lineHeight: ${q(s.lineHeight)}`, `fontWeight: ${s.fontWeight}`];
      if (s.letterSpacing) fields.push(`letterSpacing: ${q(s.letterSpacing)}`);
      if (s.fontVariantNumeric) fields.push(`fontVariantNumeric: ${q(s.fontVariantNumeric)}`);
      out.push(`  ${q(s.name)}: { ${fields.join(', ')} },`);
    }
  }
  out.push('} as const;', '', 'export type TextName = keyof typeof text;', '');
  out.push('export const spacing = {');
  for (const t of tokens.spacing.tokens) out.push(`  ${q(t.name)}: ${q(t.value)},`);
  out.push('} as const;', '');
  out.push('export const radius = {');
  for (const t of tokens.radius.tokens) out.push(`  ${q(t.name)}: ${q(t.value)},`);
  out.push('} as const;', '');
  return out.join('\n');
}

export function buildCss(tokens) {
  check(tokens);
  const names = tokens.color.tokens.map((t) => t.name);
  const out = [`/* ${HEADER} */`, ''];

  // Raw colours: one variable per token and theme. Dark follows the OS (prefers-color-scheme).
  out.push(':root {');
  for (const t of tokens.color.tokens) out.push(`  --${t.name}: ${t.value.light};`);
  out.push('}', '', '@media (prefers-color-scheme: dark) {', '  :root {');
  for (const t of tokens.color.tokens) out.push(`    --${t.name}: ${t.value.dark};`);
  out.push('  }', '}', '');

  // Tailwind v4 theme. The resets remove Tailwind's own palette, type scale and radii, so a class such as
  // bg-red-500 or text-xl does not exist: tokens.json is the only vocabulary.
  out.push('@theme static {', '  --color-*: initial;', '  --text-*: initial;', '  --radius-*: initial;', '  --font-*: initial;', '');
  out.push(`  --font-sans: var(${FONT_VARIABLE}), ${tokens.type.families.sans};`);
  out.push('  --spacing: 4px;');
  for (const t of tokens.radius.tokens) out.push(`  --${t.name}: ${t.value};`);
  for (const t of tokens.spacing.tokens) out.push(`  --${t.name}: ${t.value};`);
  for (const g of tokens.type.groups) {
    for (const s of g.styles) {
      out.push(`  --text-${s.name}: ${s.fontSize};`);
      out.push(`  --text-${s.name}--line-height: ${s.lineHeight};`);
      out.push(`  --text-${s.name}--font-weight: ${s.fontWeight};`);
      if (s.letterSpacing) out.push(`  --text-${s.name}--letter-spacing: ${s.letterSpacing};`);
    }
  }
  out.push('}', '');

  // Colours reference the raw variables so one class works in both themes.
  out.push('@theme inline {');
  for (const n of names) out.push(`  --color-${n}: var(--${n});`);
  out.push('}', '');
  return out.join('\n');
}

export function buildAll(tokens = JSON.parse(readFileSync(SOURCE, 'utf8'))) {
  return { ts: buildTs(tokens), css: buildCss(tokens) };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { ts, css } = buildAll();
  writeFileSync(TS_OUT, ts);
  writeFileSync(CSS_OUT, css);
  console.log('wrote packages/ui/src/tokens.ts and tokens.css');
}
