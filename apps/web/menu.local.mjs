import { chromium } from '@playwright/test';
import { readFileSync } from 'node:fs';
const [, , email, out] = process.argv;
const S = '/private/tmp/claude-501/-Users-user-projects-absah/609183fa-0b2a-43f4-ad83-3d8e99437033/scratchpad';
const pw = readFileSync(`${S}/pw.txt`, 'utf8').trim();
const width = Number(process.env.W ?? 1440), height = Number(process.env.H ?? 900);
const b = await chromium.launch();
const c = await b.newContext({ viewport: { width, height }, deviceScaleFactor: 1 });
const r = await c.request.post('http://localhost:4000/api/auth/sign-in/email', { data: { email, password: pw }, headers: { origin: 'http://localhost:3100' } });
if (!r.ok()) throw new Error(`login ${r.status()}`);
const p = await c.newPage();
p.on('pageerror', (e) => console.log('pageerror', e.message));
await p.goto('http://localhost:3100/hari-ini');
await p.waitForTimeout(3500);
await p.screenshot({ path: `${out}/1-bawaan-${width}.png` });
const nav = p.getByRole('navigation', { name: 'Menu utama' });
await nav.getByRole('link', { name: 'Kegiatan' }).first().hover();
await p.screenshot({ path: `${out}/2-hover-pin-${width}.png` });
for (const name of ['Kegiatan', 'Dasbor sekolah']) await nav.getByRole('button', { name: new RegExp(`^Sematkan ${name}`) }).first().click({ force: true });
await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/3-disematkan-${width}.png` });
await nav.getByRole('button', { name: 'Atur menu' }).click();
const d = p.getByRole('dialog', { name: 'Atur menu' });
await d.getByLabel('Nama grup baru').fill('Harian');
await d.getByRole('button', { name: 'Tambah grup' }).click();
const opts = await d.locator('select').first().locator('option').allTextContents();
console.log('options', opts, (await d.locator('select').evaluateAll((l) => l.map((x) => x.getAttribute('aria-label')))).join(' | '));
await d.getByLabel(/^Tempat Izin siswa$/).selectOption({ label: 'Harian' });
await d.getByLabel(/^Tempat Siswa$/).selectOption({ label: 'Harian' });
await d.getByLabel(/^Tempat Rekap/).first().selectOption({ label: 'Disematkan' });
await d.getByLabel(/^Tampilkan Gerbang di menu$/).uncheck();
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/4-atur-menu-${width}.png` });
await d.getByRole('button', { name: 'Simpan' }).click();
await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/5-hasil-${width}.png` });
console.log(await p.evaluate(() => Object.keys(localStorage).filter((k) => k.startsWith('absah.menu.')).length));
await p.reload();
await p.waitForTimeout(3500);
console.log('after reload groups', await nav.locator('p, button[aria-expanded]').allTextContents());
